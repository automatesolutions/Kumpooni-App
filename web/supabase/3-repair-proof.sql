create or replace function public.is_slip_photo(path text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.attachments a
    join public.job_slips s on s.file_id = a.file_id
    where a.storage_path = path and a.kind = 'before_photo'
  );
$$;
grant execute on function public.is_slip_photo(text) to anon, authenticated;

