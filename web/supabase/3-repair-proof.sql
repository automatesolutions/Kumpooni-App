create or replace function public.owns_repair_file(fid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.repair_files f where f.id = fid and f.user_id = auth.uid());
$$;

do $$ begin
  create policy repair_files_own on public.repair_files for all
    using (auth.uid() = user_id) with check (auth.uid() = user_id);
exception when duplicate_object then null; end $$;
do $$ begin
  create policy visits_own on public.visits for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id and public.owns_repair_file(file_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy attachments_own on public.attachments for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id and public.owns_repair_file(file_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy job_slips_own on public.job_slips for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id and public.owns_repair_file(file_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy letters_own on public.letters for all
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id and public.owns_repair_file(file_id));
exception when duplicate_object then null; end $$;
do $$ begin
  create policy offices_read on public.offices for select using (true);
exception when duplicate_object then null; end $$;

grant select on public.offices to anon, authenticated;
grant select, insert, update, delete on public.repair_files, public.visits, public.attachments,
  public.job_slips, public.letters to authenticated;
grant usage, select on all sequences in schema public to authenticated, anon;

-- ---------- Public job slip ----------

-- The shop opens /s/<code> without signing in. This returns only what the slip shows.
create or replace function public.get_job_slip(code text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'public_code', s.public_code,
    'job_text', s.job_text,
    'peso_cap', s.peso_cap,
    'dropoff_at', s.dropoff_at,
    'owner_name', s.owner_name,
    'owner_mobile', s.owner_mobile,
    'extras', s.extras,
    'created_at', s.created_at,
    'updated_at', s.updated_at,
    'shop_name', f.shop_name,
    'shop_city', f.shop_city,
    'vehicle', case when v.id is null then null else jsonb_build_object(
      'kind', v.kind,
      'year_model', v.year_model,
      'plate_no', v.plate_no,
      'make', coalesce(b.name, v.make_text),
      'model', coalesce(m.name, v.model_text)
    ) end,
    'photos', coalesce((
      select jsonb_agg(jsonb_build_object('path', a.storage_path, 'caption', a.caption) order by a.created_at)
      from public.attachments a
      where a.file_id = f.id and a.kind = 'before_photo'
    ), '[]'::jsonb)
  )
  from public.job_slips s
  join public.repair_files f on f.id = s.file_id
  left join public.vehicle v on v.id = f.vehicle_id
  left join public.brand b on b.id = v.brand_id
  left join public.model m on m.id = v.model_id
  where s.public_code = code;
$$;
grant execute on function public.get_job_slip(text) to anon, authenticated;

