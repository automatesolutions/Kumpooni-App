-- Adding a visit, proof or slip counts as activity on the file, so lists sort by it.
create or replace function public.touch_repair_file()
returns trigger
language plpgsql
as $$
begin
  update public.repair_files set updated_at = now()
  where id = coalesce(new.file_id, old.file_id);
  return coalesce(new, old);
end;
$$;
drop trigger if exists visits_touch on public.visits;
create trigger visits_touch after insert or update or delete on public.visits
  for each row execute function public.touch_repair_file();
drop trigger if exists attachments_touch on public.attachments;
create trigger attachments_touch after insert or delete on public.attachments
  for each row execute function public.touch_repair_file();

-- Two AI drafts per file per day (Philippine time). Plain template drafts don't count.
create or replace function public.letters_daily_cap()
returns trigger
language plpgsql
as $$
begin
  if new.model <> 'template' and (
    select count(*) from public.letters l
    where l.file_id = new.file_id
      and l.model <> 'template'
      and l.created_at >= (date_trunc('day', now() at time zone 'Asia/Manila') at time zone 'Asia/Manila')
  ) >= 2 then
    raise exception 'daily_draft_limit' using hint = 'You can make two AI drafts per repair file each day.';
  end if;
  return new;
end;
$$;
drop trigger if exists letters_cap on public.letters;
create trigger letters_cap before insert on public.letters
  for each row execute function public.letters_daily_cap();

