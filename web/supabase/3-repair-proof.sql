-- ---------- Repair files ----------

create table if not exists public.repair_files (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  vehicle_id uuid references public.vehicle(id) on delete set null,
  shop_name text not null check (length(trim(shop_name)) > 0),
  shop_city text,
  problem text not null check (length(trim(problem)) > 0),
  started_at date not null default current_date,
  status text not null default 'open' check (status in ('open', 'closed')),
  old_parts text not null default 'no' check (old_parts in ('no', 'yes', 'refused')),
  peso_cap numeric check (peso_cap is null or peso_cap >= 0),
  show_dealer_phrases boolean not null default false,
  lemon_hints_seen boolean not null default false
);
create index if not exists repair_files_user_idx on public.repair_files (user_id, updated_at desc);

create table if not exists public.visits (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  file_id uuid not null references public.repair_files(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  date_in date not null,
  date_out date,
  story text,
  shop_said text,
  result text check (result in ('fixed', 'not_fixed', 'worse', 'waiting_parts')),
  amount_paid numeric check (amount_paid is null or amount_paid >= 0),
  phrases text[] not null default '{}',
  check (date_out is null or date_out >= date_in)
);
create index if not exists visits_file_idx on public.visits (file_id, date_in);

create table if not exists public.attachments (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  file_id uuid not null references public.repair_files(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  kind text not null check (kind in ('estimate', 'receipt', 'before_photo', 'old_part', 'chat', 'job_order', 'other')),
  storage_path text not null unique,
  mime_type text,
  caption text,
  taken_at timestamptz
);
create index if not exists attachments_file_idx on public.attachments (file_id, created_at);

create table if not exists public.job_slips (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  file_id uuid not null unique references public.repair_files(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.users(id) on delete cascade,
  -- About 60 random bits, so the link can't be guessed.
  public_code text not null unique default substr(replace(gen_random_uuid()::text, '-', ''), 1, 16),
  job_text text not null check (length(trim(job_text)) > 0),
  peso_cap numeric check (peso_cap is null or peso_cap >= 0),
  dropoff_at timestamptz,
  owner_name text,
  owner_mobile text,
  -- [{id, text, cap, answer: 'yes' | 'no' | null, answered_at}]
  extras jsonb not null default '[]'::jsonb
);

